"""Build incident reports as a Python dictionary (for JSON) or Markdown text.

Log data can contain any text, including HTML. In the Markdown report every
value from logs or analysts is escaped, so a malicious username such as
<script>...</script> is shown as text and never runs in a Markdown viewer.
"""

import json
from datetime import datetime

from app.models import Incident, utc_now


def _iso(value: datetime | None) -> str | None:
    return value.isoformat(timespec="seconds") + "Z" if value else None


def build_report(incident: Incident) -> dict:
    alerts = sorted(incident.alerts, key=lambda a: (a.first_seen, a.id))
    verdicts = {}
    for alert in alerts:
        verdicts[alert.verdict] = verdicts.get(alert.verdict, 0) + 1

    if verdicts.get("Confirmed"):
        assessment = (
            f"{verdicts['Confirmed']} of {len(alerts)} linked alert(s) were confirmed by an analyst "
            "with a written justification."
        )
    else:
        assessment = (
            "No linked alert has been confirmed by an analyst. The activity remains suspected "
            "and should not be described as a confirmed attack."
        )

    return {
        "report_generated_at": _iso(utc_now()),
        "generated_by": "SentinelDesk",
        "incident": {
            "id": incident.id,
            "title": incident.title,
            "description": incident.description,
            "severity": incident.severity,
            "priority": incident.priority,
            "status": incident.status,
            "assigned_to": incident.assigned_to,
            "created_at": _iso(incident.created_at),
            "updated_at": _iso(incident.updated_at),
            "resolved_at": _iso(incident.resolved_at),
            "resolution_summary": incident.resolution_summary,
        },
        "assessment": assessment,
        "verdict_summary": verdicts,
        "alerts": [
            {
                "id": a.id,
                "rule_id": a.rule_id,
                "rule_name": a.rule.name,
                "mitre_technique": a.rule.mitre_technique,
                "title": a.title,
                "severity": a.severity,
                "status": a.status,
                "verdict": a.verdict,
                "first_seen": _iso(a.first_seen),
                "last_seen": _iso(a.last_seen),
                "hostname": a.hostname,
                "username": a.username,
                "source_ip": a.source_ip,
                "event_count": a.event_count,
                "detection_explanation": a.detection_explanation,
                "evidence": json.loads(a.evidence or "{}"),
                "notes": [
                    {"author": n.author, "note": n.note, "created_at": _iso(n.created_at)} for n in a.notes
                ],
            }
            for a in alerts
        ],
        "timeline": [
            {"time": _iso(t.created_at), "type": t.entry_type, "author": t.author, "message": t.message}
            for t in incident.timeline
        ],
    }


def escape_text(value) -> str:
    """Escape characters that Markdown viewers could treat as HTML."""
    if value is None or value == "":
        return "—"
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def escape_cell(value) -> str:
    """Escape a value for a Markdown table cell (no pipes or line breaks)."""
    return escape_text(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def render_markdown(report: dict) -> str:
    inc = report["incident"]
    lines = [
        f"# Incident Report #{inc['id']}: {escape_cell(inc['title'])}",
        "",
        f"_Generated by SentinelDesk at {report['report_generated_at']} (all times UTC)._",
        "",
        "## Summary",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Status | {escape_cell(inc['status'])} |",
        f"| Severity | {escape_cell(inc['severity'])} |",
        f"| Priority | {escape_cell(inc['priority'])} |",
        f"| Assigned to | {escape_cell(inc['assigned_to'])} |",
        f"| Created | {escape_cell(inc['created_at'])} |",
        f"| Resolved | {escape_cell(inc['resolved_at'])} |",
        f"| Linked alerts | {len(report['alerts'])} |",
        "",
        "### Description",
        "",
        escape_text(inc["description"]),
        "",
        "### Assessment",
        "",
        escape_text(report["assessment"]),
        "",
    ]
    if inc["resolution_summary"]:
        lines += ["### Resolution", "", escape_text(inc["resolution_summary"]), ""]

    lines += ["## Linked alerts", ""]
    if report["alerts"]:
        lines += [
            "| ID | Rule | Severity | Verdict | Host | User | Source IP | First seen | Events |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for a in report["alerts"]:
            lines.append(
                f"| {a['id']} | {escape_cell(a['rule_id'])} | {escape_cell(a['severity'])} | {escape_cell(a['verdict'])} "
                f"| {escape_cell(a['hostname'])} | {escape_cell(a['username'])} | {escape_cell(a['source_ip'])} "
                f"| {escape_cell(a['first_seen'])} | {a['event_count']} |"
            )
        lines.append("")
        for a in report["alerts"]:
            lines += [
                f"### Alert {a['id']}: {escape_cell(a['title'])}",
                "",
                f"- **Rule:** {escape_cell(a['rule_id'])} {escape_cell(a['rule_name'])} ({escape_cell(a['mitre_technique'])})",
                f"- **Why it fired:** {escape_text(a['detection_explanation'])}",
                f"- **Status / verdict:** {escape_cell(a['status'])} / {escape_cell(a['verdict'])}",
            ]
            if a["notes"]:
                lines.append("- **Analyst notes:**")
                for n in a["notes"]:
                    lines.append(f"  - {escape_cell(n['created_at'])} ({escape_cell(n['author'])}): {escape_cell(n['note'])}")
            lines.append("")
    else:
        lines += ["No alerts are linked to this incident.", ""]

    lines += ["## Timeline", ""]
    for t in report["timeline"]:
        lines.append(f"- {escape_cell(t['time'])} [{escape_cell(t['type'])}] {escape_cell(t['author'])}: {escape_cell(t['message'])}")
    lines.append("")
    return "\n".join(lines)
